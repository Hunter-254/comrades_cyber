export function catalogHelp(prefix, name, entries, referenceCount, commandName = 'tenzi') {
  const preview = entries.slice(0, 18).map((title, index) => `${index + 1}. ${title}`).join('\n');
  return `╭─⌈ 🎵 *${name.toUpperCase()}* ⌋\n│\n├─⊷ *${prefix}${commandName} <title or number>*\n│  └⊷ Search and download one hymn\n├─⊷ *${prefix}${commandName} list*\n│  └⊷ Show featured titles\n│\n${preview}\n│\n├─⊷ Reference collection: approximately ${referenceCount} hymns\n╰⊷ Enter a title or number to search the full collection online.`;
}

export function resolveCatalogQuery(input, entries, prefixText) {
  const value = String(input || '').trim();
  if (!value) return `${prefixText} hymn`;
  const index = Number.parseInt(value, 10);
  if (Number.isInteger(index) && index >= 1 && index <= entries.length) return `${prefixText} ${entries[index - 1]}`;
  return `${prefixText} ${value}`;
}
